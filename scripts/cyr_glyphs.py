# Cyrillic glyphs for the main dialogue font (cell 16x15).
# Only the white stroke ('#') is drawn here; the grey shadow is generated
# automatically at (+1,+1), exactly like every original glyph.
# Rows: capitals 0-10, lowercase x-height 3-10, descenders 11-13.

G = {}

def g(ch, rows, top=0):
    rows = [r for r in rows.strip('\n').split('\n')]
    G[ch] = (top, [r.strip() for r in rows])

