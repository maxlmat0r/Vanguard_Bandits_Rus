# Russian letters that reuse existing Latin glyphs (identical shapes)
HOMO = {'В':'B','Е':'E','Ё':'E','О':'O','Р':'P','С':'C','Т':'T','Х':'X',
        'а':'a','е':'e','ё':'e','о':'o','р':'p','с':'c','у':'y','х':'x'}
# capital hard/soft signs and Ы only occur in ALL-CAPS words: use lowercase glyphs
CAPS_AS_LOWER = {'Ъ':'ъ','Ы':'ы','Ь':'ь','Й':'й'}   # Й: '+' is needed as a symbol in UI

# ASCII symbols never used in dialogue: their glyph slots are reused
SYMBOL_SLOTS = '*<=>@[\\]^_{|}`'

def build_charmap():
    """Russian char -> game byte. 32 letters go to new glyphs (codes 0xB0-0xCF),
    15 more replace unused ASCII symbol glyphs."""
    letters = [c for c in G if c not in CAPS_AS_LOWER]
    assert len(letters) == 32 + len(SYMBOL_SLOTS), len(letters)
    in_slots = ['Щ','Ц','Э','Ю','Ф','Ж','Ш','Ч','З','У','Г','Д','Л','Я']
    common = [c for c in letters if c not in in_slots]
    cmap = {}
    for i, c in enumerate(common):
        cmap[c] = 0xB0 + i
    for c, s in zip(in_slots, SYMBOL_SLOTS):
        cmap[c] = ord(s)
    for c, l in HOMO.items():
        cmap[c] = ord(l)
    for c, l in CAPS_AS_LOWER.items():
        cmap[c] = cmap[l]
    return cmap

CHARMAP = build_charmap()

def encode(text):
    """Russian text -> game bytes. {XX} (two hex digits) inserts a raw control byte."""
    out = bytearray()
    i = 0
    while i < len(text):
        ch = text[i]
        if ch == '{' and text[i+3:i+4] == '}':
            out.append(int(text[i+1:i+3], 16)); i += 4; continue
        i += 1
        if ch in CHARMAP: out.append(CHARMAP[ch])
        elif ch == '—' or ch == '–': out += b'--'
        elif ch == '«' or ch == '»': out.append(ord('"'))
        elif ch == '…': out += b'...'
        elif ord(ch) < 0x80:
            if ch in SYMBOL_SLOTS:
                raise ValueError(f'symbol {ch!r} is now a Cyrillic glyph')
            out.append(ord(ch))
        else:
            raise ValueError(f'no glyph for {ch!r}')
    return bytes(out)


# ---- pixel width (same numbers the build writes into the game's width table)
_ORIG_W = None
ORIG_FONT_WIDTHS = ('0403050a070a0903040405060306020507070707070707070707020304050406040707070707070708'
                    '040607070b0807070707070808070b0707070307030307030707050705050607040307040b0706070706050408060b0606'
                    '0704020407070f0f0f0f0f0f0f0f0f0f0f0f0f0f0f0f')

def _widths():
    global _ORIG_W
    if _ORIG_W is None:
        import os
        # glyph widths of the original font (SLUS_010.70 @0x5524c), so checks run without game files
        w = bytearray(bytes.fromhex(ORIG_FONT_WIDTHS)) + bytes(0x20)
        for ch, (top, rows) in G.items():
            if ch in CAPS_AS_LOWER: continue
            code = CHARMAP[ch]
            gl = code - 0x20 if code < 0x80 else code - 0x40
            w[gl] = max(max((i for i, c in enumerate(r) if c == '#'), default=-1) for r in rows) + 1
        _ORIG_W = w
    return _ORIG_W

def line_px(encoded_line):
    w = _widths()
    return sum(w[(c - 0x20) if c < 0x80 else (c - 0x40)] + 1 for c in encoded_line if c >= 0x20)


